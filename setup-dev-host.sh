#!/bin/bash
# VEIL dev-host setup — run after a VM replacement.
# Home directory (~) persists across deployments; system packages
# installed with apt do NOT. This script reinstalls what VEIL needs.
# Bubblewrap is the only apt package VEIL currently requires;
# libseccomp is part of the base image (checked, not installed here).
set -e
if ! command -v bwrap >/dev/null 2>&1; then
  echo "bwrap missing — installing bubblewrap..."
  if [ -f /var/cache/apt/archives/bubblewrap_0.9.0-1ubuntu0.3_amd64.deb ]; then
    dpkg -i /var/cache/apt/archives/bubblewrap_0.9.0-1ubuntu0.3_amd64.deb
  else
    apt-get update && apt-get install -y bubblewrap
  fi
fi
bwrap --version
python3 -c "import ctypes; ctypes.CDLL('libseccomp.so.2'); print('libseccomp ok')"
# The Security Center runs as root and looks for veil-browser on PATH,
# but /usr/local/bin does not survive a VM replacement either.
# Recreate the symlink on every restore so /api/state reports the CLI available.
CLI_BIN="$(dirname "$0")/../veil-browser-cli/target/release/veil-browser"
if [ -x "$CLI_BIN" ]; then
  ln -sf "$(readlink -f "$CLI_BIN")" /usr/local/bin/veil-browser
  echo "veil-browser linked: $(readlink /usr/local/bin/veil-browser)"
else
  echo "veil-browser binary not found at $CLI_BIN — skipping symlink (non-fatal)"
fi
# Reinstall VEIL systemd units if they exist in the repo. /etc does not
# survive a VM replacement; the units live in veil-os/systemd/.
if [ -f "$(dirname "$0")/systemd/install.sh" ] && [ -d /run/systemd/system ]; then
  bash "$(dirname "$0")/systemd/install.sh" || echo "systemd unit install failed (non-fatal)"
fi
# The browser daemon only starts its egress-proxy shim when HTTPS_PROXY
# is set, and the CLI passes a fresh proxy token to the daemon on every
# invocation — the token rotates on every agent invocation, so a value
# baked into the repo unit would go stale immediately. The token is a
# secret: it lives only in this generated drop-in under /etc (wiped on
# every VM replacement, regenerated here), never in the repo.
# Regenerate on every restore so the Security Center always gets a
# token issued for the current boot/invocation.
if [ -n "${HTTPS_PROXY:-}" ] && [ -d /run/systemd/system ]; then
  mkdir -p /etc/systemd/system/veil-security-center.service.d
  {
    echo "# Generated by setup-dev-host.sh — proxy token, do not commit."
    echo "[Service]"
    echo "Environment=\"HTTPS_PROXY=$HTTPS_PROXY\""
    [ -n "${https_proxy:-}" ] && echo "Environment=\"https_proxy=$https_proxy\""
    [ -n "${HTTP_PROXY:-}" ] && echo "Environment=\"HTTP_PROXY=$HTTP_PROXY\""
    [ -n "${http_proxy:-}" ] && echo "Environment=\"http_proxy=$http_proxy\""
    [ -n "${NO_PROXY:-}" ] && echo "Environment=\"NO_PROXY=$NO_PROXY\""
    [ -n "${no_proxy:-}" ] && echo "Environment=\"no_proxy=$no_proxy\""
  } > /etc/systemd/system/veil-security-center.service.d/proxy.conf
  systemctl daemon-reload
  systemctl restart veil-security-center.service 2>/dev/null || true
  echo "proxy drop-in written, Security Center restarted"
fi
echo "dev host ready"
